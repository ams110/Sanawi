import type { useTranslation } from 'react-i18next'

/**
 * نوع دالّة الترجمة حين تُمرَّر إلى دالّة مساعدة خارج المكوّن.
 *
 * كتابتها يدوياً `(key: string) => string` تُسقط تدقيق المفاتيح الذي بُني
 * له i18next.d.ts كلّه: `t` المولَّدة تقبل مفاتيح الترجمة الحرفية وحدها،
 * و`string` أوسع منها فلا تنطبق. الاشتقاق من المصدر يبقي الحارس قائماً
 * ويجعل مفتاحاً مكسوراً في دالّةٍ مساعدة خطأَ بناءٍ كما هو في المكوّن.
 */
export type Translate = ReturnType<typeof useTranslation>['t']
