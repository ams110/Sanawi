import { describe, expect, it } from 'vitest'
import { readAmount } from './amount'

describe('قراءة مبلغٍ مكتوب', () => {
  it('العدد الصحيح والعشري', () => {
    expect(readAmount('500')).toBe(500)
    expect(readAmount('12.50')).toBe(12.5)
  })

  /*
   * الفاصلة تُقبل: لوحة الأرقام العربية على أندرويد تعطي «٫» أو «,» لا «.»،
   * والحقل الرقمي يرفضها — فيقف المستخدم أمام حقلٍ لا يقبل ما تكتبه لوحته.
   */
  it('الفاصلة العشرية بأشكالها', () => {
    expect(readAmount('12,50')).toBe(12.5)
    expect(readAmount('12٫50')).toBe(12.5)
  })

  it('الأرقام العربية-الهندية', () => {
    expect(readAmount('١٢٥')).toBe(125)
    expect(readAmount('١٢٫٥')).toBe(12.5)
  })

  /*
   * الفراغ ليس صفراً.
   *
   * الصفر قيمةٌ يكتبها المستخدم عمداً (فاتورةٌ بصفر)، وخلطه بالفراغ يجعل «لم
   * يكتب شيئاً» و«كتب صفراً» حالةً واحدة — فيستحيل أن يكون للحقل الفارغ معنًى
   * افتراضي (القسط) وللصفر معنًى آخر.
   */
  it('الفارغ null والصفر صفر', () => {
    expect(readAmount('')).toBe(null)
    expect(readAmount('   ')).toBe(null)
    expect(readAmount('0')).toBe(0)
  })

  // الحالات الوسيطة أثناء الكتابة: «12.» ليست رقماً تامّاً، والحقل الرقمي
  // كان يمسحها تحت الإصبع. هنا تُقرأ 12 ويبقى النصّ كما كتبه صاحبه.
  it('الحالة الوسيطة أثناء الكتابة لا تنهار', () => {
    expect(readAmount('12.')).toBe(12)
    expect(readAmount('12,')).toBe(12)
  })

  it('ما ليس رقماً يبقى null', () => {
    expect(readAmount('كذا')).toBe(null)
    expect(readAmount('12.5.5')).toBe(null)
  })

  it('السالب يُقرأ كما كُتب — والرفض عند الإرسال لا عند القراءة', () => {
    expect(readAmount('-50')).toBe(-50)
  })
})
